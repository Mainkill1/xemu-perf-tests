def build_manifest(fixtures: dict[str, bytes]) -> dict:
    records = []
    for fixture_id, path, encoding, channels, rate, frames, description in FIXTURE_METADATA:
        payload = fixtures[path]
        records.append({
            "id": fixture_id,
            "path": path,
            "disc_path": "D:\\audio\\" + path.replace("/", "\\"),
            "encoding": encoding,
            "channels": channels,
            "sample_rate_hz": rate,
            "frames": frames,
            "bytes": len(payload),
            "sha256": hashlib.sha256(payload).hexdigest(),
            "fnv1a64": f"{fnv1a64(payload):016x}",
            "description": description,
        })
    return {
        "schema_version": 1,
        "license": "Unlicense (repository LICENSE)",
        "source": "Procedurally generated by utils/generate_audio_fixtures.py; no third-party recordings.",
        "fixtures": records,
        "notes": {
            "midi": "Not included: MIDI/DirectMusic would test a sequencing/synthesis layer, not the MCPX VP/GP/EP hot paths targeted by this suite.",
            "adpcm": "The encoded blocks decode to 65 frames by IMA block semantics. The pinned xemu VP currently uses ADPCM_SAMPLES_PER_BLOCK=64 (with an in-source FIXME), so focused tests should treat the 65-frame golden as decoder truth and separately characterize VP consumption.",
            "u8": "U8 VP samples are generated deterministically at runtime from the integer S16 signal source. This avoids relying on a fragile checked-in high-byte raw payload while preserving exact repeatability.",
        },
    }


ENCODING_CPP = {
    "wav_pcm_s16": "kWavPcmS16",
    "vp_pcm_s16": "kVpPcmS16",
    "vp_pcm_s24_b32": "kVpPcmS24B32",
    "vp_pcm_s32": "kVpPcmS32",
    "vp_ima_adpcm": "kVpImaAdpcm",
    "golden_pcm_s16": "kGoldenPcmS16",
}


def render_cpp_catalog(manifest: dict) -> str:
    lines = [
        "// Generated by utils/generate_audio_fixtures.py. Do not edit by hand.",
        "static constexpr AudioFixtureSpec kAudioFixtureSpecs[] = {",
    ]
    for fixture in manifest["fixtures"]:
        path = fixture["disc_path"].replace("\\", "\\\\")
        lines.append(
            f'    {{"{fixture["id"]}", "{path}", '
            f'AudioFixtureEncoding::{ENCODING_CPP[fixture["encoding"]]}, '
            f'{fixture["channels"]}U, {fixture["sample_rate_hz"]}U, '
            f'{fixture["frames"]}U, {fixture["bytes"]}U, '
            f'0x{fixture["fnv1a64"]}ULL}},'
        )
    lines.extend([
        "};",
        "static constexpr size_t kAudioFixtureSpecCount =",
        "    sizeof(kAudioFixtureSpecs) / sizeof(kAudioFixtureSpecs[0]);",
        "",
    ])
    return "\n".join(lines)


def generated_outputs() -> tuple[dict[str, bytes], str, str]:
    fixtures = build_fixtures()
    manifest = build_manifest(fixtures)
    manifest_text = json.dumps(manifest, indent=2) + "\n"
    catalog_text = render_cpp_catalog(manifest)
    return fixtures, manifest_text, catalog_text


def check() -> int:
    fixtures, manifest_text, catalog_text = generated_outputs()
    mismatches = []
    for relative_path, expected in fixtures.items():
        path = AUDIO_ROOT / relative_path
        if not path.exists() or path.read_bytes() != expected:
            mismatches.append(str(path.relative_to(ROOT)))
    if not MANIFEST_PATH.exists() or MANIFEST_PATH.read_text(encoding="utf-8") != manifest_text:
        mismatches.append(str(MANIFEST_PATH.relative_to(ROOT)))
    if not CATALOG_PATH.exists() or CATALOG_PATH.read_text(encoding="utf-8") != catalog_text:
        mismatches.append(str(CATALOG_PATH.relative_to(ROOT)))

    if mismatches:
        print("audio fixture generation is stale:")
        for path in mismatches:
            print(f"  {path}")
        return 1
    print(f"audio fixtures current: {len(fixtures)} files")
    return 0


def write() -> None:
    fixtures, manifest_text, catalog_text = generated_outputs()
    for relative_path, payload in fixtures.items():
        path = AUDIO_ROOT / relative_path
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
    MANIFEST_PATH.write_text(manifest_text, encoding="utf-8")
    CATALOG_PATH.write_text(catalog_text, encoding="utf-8")
    print(f"wrote {len(fixtures)} audio fixtures")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        return check()
    write()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
